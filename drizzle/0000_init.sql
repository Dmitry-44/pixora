CREATE TABLE "generations" (
	"id" uuid PRIMARY KEY DEFAULT uuidv7() NOT NULL,
	"telegram_user_id" bigint NOT NULL,
	"chat_id" bigint NOT NULL,
	"message_id" bigint NOT NULL,
	"status" text NOT NULL,
	"user_prompt" text NOT NULL,
	"model_prompt" text NOT NULL,
	"model_params" jsonb NOT NULL,
	"model" text NOT NULL,
	"polza_generation_id" text,
	"result_url" text,
	"cost_rub" numeric,
	"failure_reason" text,
	"attempts" integer DEFAULT 0 NOT NULL,
	"poll_count" integer DEFAULT 0 NOT NULL,
	"created_at" timestamp with time zone DEFAULT now() NOT NULL,
	"submitted_at" timestamp with time zone,
	"completed_at" timestamp with time zone,
	"delivered_at" timestamp with time zone,
	"delivery_failed_at" timestamp with time zone,
	CONSTRAINT "generations_chat_id_message_id_unique" UNIQUE("chat_id","message_id"),
	CONSTRAINT "generations_status_check" CHECK ("generations"."status" IN ('accepted', 'submitted', 'completed', 'failed')),
	CONSTRAINT "generations_failure_reason_check" CHECK ("generations"."failure_reason" IN ('moderation', 'insufficient_funds', 'invalid_request', 'misconfigured', 'provider_failed', 'provider_unavailable', 'timeout', 'internal'))
);
